CREATE TABLE IF NOT EXISTS "addresses" (
    "id" TEXT NOT NULL DEFAULT gen_random_uuid()::text,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "address" TEXT NOT NULL,
    "city" TEXT NOT NULL,
    "state" TEXT NOT NULL,
    "zip" TEXT NOT NULL,
    "duration" TEXT NOT NULL,
    "applicationId" TEXT NOT NULL,
    CONSTRAINT "addresses_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "addresses_applicationId_fkey" FOREIGN KEY ("applicationId") REFERENCES "applications"("id") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS "employment" (
    "id" TEXT NOT NULL DEFAULT gen_random_uuid()::text,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "employer" TEXT NOT NULL,
    "position" TEXT NOT NULL,
    "startDate" TEXT NOT NULL,
    "endDate" TEXT NOT NULL,
    "salary" TEXT NOT NULL,
    "reasonForLeaving" TEXT NOT NULL,
    "supervisorName" TEXT,
    "supervisorPhone" TEXT,
    "canContact" BOOLEAN NOT NULL DEFAULT true,
    "applicationId" TEXT NOT NULL,
    CONSTRAINT "employment_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "employment_applicationId_fkey" FOREIGN KEY ("applicationId") REFERENCES "applications"("id") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS "accidents" (
    "id" TEXT NOT NULL DEFAULT gen_random_uuid()::text,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "date" TEXT NOT NULL,
    "description" TEXT NOT NULL,
    "fatalities" BOOLEAN NOT NULL DEFAULT false,
    "injuries" BOOLEAN NOT NULL DEFAULT false,
    "location" TEXT,
    "charges" TEXT,
    "applicationId" TEXT NOT NULL,
    CONSTRAINT "accidents_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "accidents_applicationId_fkey" FOREIGN KEY ("applicationId") REFERENCES "applications"("id") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS "violations" (
    "id" TEXT NOT NULL DEFAULT gen_random_uuid()::text,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "date" TEXT NOT NULL,
    "violation" TEXT NOT NULL,
    "location" TEXT NOT NULL,
    "penalty" TEXT,
    "applicationId" TEXT NOT NULL,
    CONSTRAINT "violations_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "violations_applicationId_fkey" FOREIGN KEY ("applicationId") REFERENCES "applications"("id") ON DELETE CASCADE ON UPDATE CASCADE
