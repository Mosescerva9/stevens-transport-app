    "currentDuration" TEXT NOT NULL,
    "livedHereThreeYears" BOOLEAN NOT NULL DEFAULT false,
    "licenseNumber" TEXT NOT NULL,
    "licenseState" TEXT NOT NULL,
    "licenseExpiration" TEXT NOT NULL,
    "cdlClass" TEXT,
    "endorsements" TEXT,
    "restrictions" TEXT,
    "licenseImageFront" TEXT,
    "licenseImageBack" TEXT,
